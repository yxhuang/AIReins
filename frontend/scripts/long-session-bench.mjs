import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { performance } from 'node:perf_hooks';
process.env.WORKBENCH_HOME = mkdtempSync(join(tmpdir(), 'wb-long-bench-'));
const persistence = await import('../../server/persistence.ts');
const { SessionManager } = await import('../../server/session-manager.ts');
const render = await import('../src/render-items.ts');
const events = [];
const add = (type, payload = {}) => events.push({ seq: events.length + 1, type, payload, sessionId: 'bench', agentId: 'main', timestamp: '2026-10-05T00:00:00Z' });
for (let i = 0; i < 1000; i++) {
  add('user_message', { text: `turn ${i}` });
  add('thought_delta', { text: 'thinking' });
  add('tool_call_started', { toolCallId: `t${i}`, toolName: 'Read' });
  add('tool_call_completed', { toolCallId: `t${i}`, result: 'ok' });
  add('agent_text_delta', { text: i === 999 ? 'x'.repeat(50 * 1024) : 'answer' });
  if (i < 999) add('turn_completed');
}
const path = persistence.transcriptPathFor('bench');
mkdirSync(join(process.env.WORKBENCH_HOME, 'transcripts'));
writeFileSync(path, events.map(e => JSON.stringify(e) + '\n').join(''));
persistence.saveRegistry([{ id: 'bench', agent: 'codex', agentId: 'main', cwd: process.cwd(), status: 'dead', seq: events.length, config: {}, createdAt: events[0].timestamp, lastActivityAt: events[0].timestamp, transcriptPath: path }]);
const manager = new SessionManager();
const measure = (fn, n = 30) => { for (let i = 0; i < 3; i++) fn(); const start = performance.now(); for (let i = 0; i < n; i++) fn(); return (performance.now() - start) / n; };
const incremental = render.createRenderItemsBuilder?.('codex');
if (incremental) incremental.update(events, 0);
const delta = { ...events.at(-1), seq: events.length + 1, payload: { text: ' delta' } };
let seq = delta.seq;
const frontend = measure(() => { events.push({ ...delta, seq: seq++ }); if (incremental) incremental.update(events, 0); else render.buildRenderItems(events, 'codex'); });
const tail = measure(() => manager.getSnapshot('bench', true));
const cursor = manager.getSnapshot('bench', true).firstSeq;
const before = measure(() => manager.getEventsBefore('bench', cursor));
const writePath = persistence.transcriptPathFor('writes');
const start = performance.now();
for (let i = 0; i < 1000; i++) persistence.appendTranscript(writePath, { ...delta, seq: i + 1 });
persistence.flushTranscripts?.();
const append = performance.now() - start;
console.log(JSON.stringify({ events: 5999, finalTextBytes: 51200, mode: incremental ? 'after' : 'before', frontendDeltaMs: frontend, tailSnapshotMs: tail, beforeSeqMs: before, append1000Ms: append, tempHome: process.env.WORKBENCH_HOME }, null, 2));
await manager.shutdown();
